  Per-map SVG metadata for `GameLive.WorldMap` — GENERATED by `scripts/trace_maps.py`
  together with the `world_map/<map>_map_defs.html.heex` templates (territory
  outlines, links and region borders as static SVG `<defs>`). Do not edit by hand.

  Everything is traced from the legacy ASP.NET project's `Web/wwwroot/maps/<map>/
  <tech>0.gif` silhouettes (the LiveView app no longer ships those sprites) placed at
  their `MapInfo.render_info/2` offsets, so the shapes and the legacy 800x480 board
  coordinates are exactly the sprite board's; only the rendering changes (vector fills
  styled by CSS instead of nine pre-colored GIFs per territory). Links come from
  `MapInfo` adjacency — any two linked areas whose silhouettes are more than a few
  pixels apart get a line between their closest boundary points (sea lanes on the world
  map, where Alaska <-> Pevek wraps off the board edges; the arrow routes on elements).
  Region borders are the traced union of each region's areas.

  A label anchor is the approximate pole of inaccessibility (last pixels to survive
  repeated erosion), so army counts land inside the widest part of a territory —
  not at the bounding-box center, which for Alaska or Indonesia falls in the sea.

  Regenerate (from `liveview/`):

      python3 -m venv .venv && .venv/bin/pip install pillow numpy
      .venv/bin/python scripts/trace_maps.py . && mix format
  """

